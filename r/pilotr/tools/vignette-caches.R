# Regenerate the cached results that the power and precision vignettes read.
#
# Three chunks of those vignettes fit hundreds of mixed models, which takes far longer than a
# package check allows. The vignettes therefore show them with eval = FALSE and read their results
# from files in vignettes/. This script runs those chunks and writes:
#
#   power-mixed-cache.rds      the object power_mixed() returns, kept whole so that the vignette
#                              prints the fit accounting a live run prints
#   power-curve-cache.csv      every column power_curve_mixed() returns
#   precision-curve-cache.csv  every column precision_curve() returns
#   cache-fingerprint.txt      what the caches rest on, which tests/testthat/test-vignette-caches.R
#                              recomputes
#
# The two tables end with the versions of pilotr and lme4 that produced them, and the object
# carries the same two versions as its "versions" attribute. The fingerprint holds the first three
# seeds that replicate_seeds() draws from the vignettes' seed of 1. For each vignette, it adds a
# checksum of the chunks that produced its caches and one of its first replicate's model_data().
# A change to the seed rule, to the generative engine or to the code a cached chunk shows
# therefore fails the test until this script has been run again. The fingerprint fits no model. A
# change to how the analyses fit or summarise the replicates, or a new version of lme4, leaves it as
# it was, and the caches then have to be regenerated by hand.
#
# Run it from r/pilotr whenever one of those changes, or the columns an analysis returns, and
# commit the four files it writes:
#
#   Rscript tools/vignette-caches.R [workers]
#
# The chunks are read from the vignettes by their labels and evaluated as they stand, except that
# power_mixed(), power_curve_mixed() and precision_curve() are given `workers`. The worker count
# changes how long they take and never what they return. PSOCK workers load whichever pilotr is
# installed in their library, and a copy installed earlier would fit the replicates with its own
# code. The script therefore installs this source tree into a temporary library and puts that
# library first, for itself and, through R_LIBS, for its workers, and installs nothing anywhere
# else. On two workers a run takes about 35 minutes, most of them spent on the precision sweep's
# 1,600 fits. Leave this file alone while a run of it is going, since Rscript reads a script as it
# runs it, and a run reads on into whatever the file holds by the time main() returns.

# Each vignette with cached results, its chunks whose results are cached, the object each chunk
# creates and the file that object is written to.
VIGNETTE_CACHES <- list(
  "power-analysis.Rmd" = list(
    list(label = "power-mixed", object = "pm", file = "power-mixed-cache.rds"),
    list(label = "power-curve", object = "curve", file = "power-curve-cache.csv")),
  "precision-rope.Rmd" = list(
    list(label = "precision-curve", object = "prc", file = "precision-curve-cache.csv")))

# The chunk that builds each vignette's specification, spec_c, under the same label in both.
SPEC_CHUNK <- "priming-spec"

# The code of the chunk labelled `label` in the R Markdown file `rmd`, as lines. readLines()
# accepts either line ending, so a checkout with CRLF endings yields the same lines.
vignette_chunk <- function(rmd, label) {
  lines <- readLines(rmd, encoding = "UTF-8", warn = FALSE)
  open <- grep(sprintf("^```\\{r %s[,}]", label), lines)
  if (length(open) != 1L)
    stop(sprintf("%s has %d chunks labelled '%s', where one was expected.",
                 rmd, length(open), label), call. = FALSE)
  close <- open + which(grepl("^```[[:space:]]*$", lines[-seq_len(open)]))[1]
  if (is.na(close))
    stop(sprintf("The chunk labelled '%s' in %s is not closed.", label, rmd), call. = FALSE)
  lines[seq.int(open + 1L, length.out = close - open - 1L)]
}

# The MD5 checksum of some lines, joined by a newline and taken over their UTF-8 bytes, so that it
# is the same on every platform.
md5_lines <- function(lines) {
  path <- tempfile()
  on.exit(unlink(path))
  writeBin(charToRaw(enc2utf8(paste(lines, collapse = "\n"))), path)
  unname(tools::md5sum(path))
}

# The first replicate of an analysis of `spec`, simulated and prepared as the replicate loop does
# it, written as lines of text. Doubles are written to eight significant digits. The last bits of
# a log or an exponential differ between platforms' maths libraries, and the rounding keeps those
# differences out of the checksum. A change to the seeds or to the engine moves the leading digits
# of nearly every value.
first_replicate_lines <- function(spec) {
  first <- spec
  first[["seed"]] <- replicate_seeds(spec[["seed"]], 1)[1]
  d <- model_data(spec, simulate_design(first, validate = FALSE))
  cols <- lapply(d, function(v) if (is.double(v)) sprintf("%.8g", v) else as.character(v))
  c(paste(names(d), collapse = ","), do.call(paste, c(unname(cols), sep = ",")))
}

# The fingerprint of the cached results, as a named character vector. `envir` is where the
# specification chunks are evaluated, and it has to reach build_spec().
cache_fingerprint <- function(dir = "vignettes", envir = parent.frame()) {
  out <- c("Replicate-seeds" = paste(sprintf("%.0f", replicate_seeds(1, 3)), collapse = " "))
  for (rmd in names(VIGNETTE_CACHES)) {
    path <- file.path(dir, rmd)
    spec_code <- vignette_chunk(path, SPEC_CHUNK)
    env <- new.env(parent = envir)
    eval(parse(text = spec_code, keep.source = FALSE), envir = env)
    cached <- unlist(lapply(VIGNETTE_CACHES[[rmd]], function(k) vignette_chunk(path, k$label)))
    stem <- sub("[.]Rmd$", "", rmd)
    out[paste0(stem, "-code")] <- md5_lines(c(spec_code, cached))
    out[paste0(stem, "-data")] <- md5_lines(first_replicate_lines(env$spec_c))
  }
  out
}

# Install the source tree in the working directory into a temporary library, and put that library
# first for this session and, through R_LIBS, for the worker processes it starts.
install_source_tree <- function() {
  lib <- tempfile("pilotr-lib-")
  dir.create(lib)
  log <- tools::Rcmd(c("INSTALL", "--no-docs", shQuote(paste0("--library=", lib)), "."),
                     stdout = TRUE, stderr = TRUE)
  status <- attr(log, "status")
  if (!is.null(status) && status != 0L) {
    writeLines(log)
    stop("Installing pilotr from this source tree failed.", call. = FALSE)
  }
  libs <- c(lib, strsplit(Sys.getenv("R_LIBS"), .Platform$path.sep, fixed = TRUE)[[1]])
  Sys.setenv(R_LIBS = paste(libs[nzchar(libs)], collapse = .Platform$path.sep))
  .libPaths(c(lib, .libPaths()))
  lib
}

# Write one cached result, with the versions that produced it.
write_cache <- function(x, path, versions) {
  if (grepl("[.]rds$", path)) {
    attr(x, "versions") <- versions
    saveRDS(x, path)
  } else {
    x$pilotr_version <- versions[["pilotr"]]
    x$lme4_version <- versions[["lme4"]]
    utils::write.csv(x, path, row.names = FALSE)
  }
}

main <- function(args = commandArgs(trailingOnly = TRUE)) {
  workers <- if (length(args)) suppressWarnings(as.integer(args[[1]])) else 1L
  if (length(args) > 1L || is.na(workers) || workers < 1L)
    stop("Usage, from r/pilotr: Rscript tools/vignette-caches.R [workers]", call. = FALSE)
  if (!file.exists("DESCRIPTION") ||
      !identical(unname(read.dcf("DESCRIPTION", fields = "Package")[1, 1]), "pilotr"))
    stop("Run this script from r/pilotr, the directory that holds pilotr's DESCRIPTION.",
         call. = FALSE)

  lib <- install_source_tree()
  library(pilotr, lib.loc = lib)
  versions <- c(pilotr = as.character(utils::packageVersion("pilotr", lib.loc = lib)),
                lme4 = as.character(utils::packageVersion("lme4")))
  message(sprintf("pilotr %s from this source tree, lme4 %s, %d worker%s", versions[["pilotr"]],
                  versions[["lme4"]], workers, if (workers == 1L) "" else "s"))

  for (rmd in names(VIGNETTE_CACHES)) {
    path <- file.path("vignettes", rmd)
    env <- new.env(parent = globalenv())
    # The three analyses under the names the chunks call them by, with `workers` added.
    env$power_mixed <- function(...) pilotr::power_mixed(..., workers = workers)
    env$power_curve_mixed <- function(...) pilotr::power_curve_mixed(..., workers = workers)
    env$precision_curve <- function(...) pilotr::precision_curve(..., workers = workers)
    eval(parse(text = vignette_chunk(path, SPEC_CHUNK), keep.source = FALSE), envir = env)
    for (k in VIGNETTE_CACHES[[rmd]]) {
      started <- Sys.time()
      eval(parse(text = vignette_chunk(path, k$label), keep.source = FALSE), envir = env)
      write_cache(get(k$object, envir = env, inherits = FALSE), file.path("vignettes", k$file),
                  versions)
      message(sprintf("%s, chunk '%s': wrote vignettes/%s in %.1f minutes", rmd, k$label, k$file,
                      as.numeric(difftime(Sys.time(), started, units = "mins"))))
    }
  }

  fingerprint <- cache_fingerprint("vignettes", envir = globalenv())
  writeLines(c("Written-by: tools/vignette-caches.R",
               paste0(names(fingerprint), ": ", fingerprint)),
             "vignettes/cache-fingerprint.txt")
  message("wrote vignettes/cache-fingerprint.txt")
}

# Run when called by Rscript, and only define the functions above when sourced, as the test does.
if (sys.nframe() == 0L) main()
